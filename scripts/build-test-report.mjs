#!/usr/bin/env node
/**
 * Builds docs/TEST_REPORT.md (English) and docs/TEST_REPORT.pt-BR.md (Portuguese)
 * from machine-readable results only — nothing is typed by hand:
 *
 *   tests/acceptance/test-plan.json               test cases, requirements, expected results
 *   docs/test-results/vitest-results.json         every automated test (npm run test:evidence)
 *   docs/test-results/acceptance-evidence.json    values observed by the acceptance tests
 *   docs/test-results/e2e-results.json            browser checks + screenshots (npm run test:e2e)
 *
 *   npm run test:report
 */
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const plan = read("tests/acceptance/test-plan.json");
const vitest = read("docs/test-results/vitest-results.json");
const evidence = read("docs/test-results/acceptance-evidence.json").cases;
const e2e = existsSync(join(ROOT, "docs/test-results/e2e-results.json")) ? read("docs/test-results/e2e-results.json") : null;
const pkgVersion = (name) => {
  try {
    return JSON.parse(readFileSync(join(ROOT, "node_modules", name, "package.json"), "utf8")).version;
  } catch {
    return "?";
  }
};
const git = (cmd) => {
  try {
    return execSync(`git ${cmd}`, { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
};

// ---------------------------------------------------------------------------
// Data
// ---------------------------------------------------------------------------

const assertions = vitest.testResults.flatMap((f) =>
  f.assertionResults.map((a) => ({ ...a, file: relative(ROOT, f.name) })),
);
const acceptance = Object.fromEntries(
  assertions
    .filter((a) => /^S\d-\d\d /.test(a.title))
    .map((a) => [a.title.slice(0, 5), { status: a.status, durationMs: a.duration, title: a.title }]),
);
const caseResult = (id) => acceptance[id]?.status ?? "missing";
const e2eFor = (scenario) => (e2e?.results ?? []).filter((r) => r.id.startsWith(`E2E-${scenario}-`));
const commit = git("rev-parse HEAD");
const dirty = git("status --porcelain")
  .split("\n")
  .filter((l) => l && !/docs\/test-results\/|docs\/TEST_REPORT/.test(l));
const acceptancePassed = plan.cases.filter((c) => caseResult(c.id) === "passed").length;
const e2ePassed = e2e ? e2e.results.filter((r) => r.status === "passed").length : 0;
const allPassed =
  acceptancePassed === plan.cases.length &&
  vitest.numFailedTests === 0 &&
  (!e2e || (e2e.failed === 0 && e2e.pageErrors.length === 0));
const date = new Date(vitest.startTime).toISOString().replace("T", " ").slice(0, 16) + " UTC";

const files = Object.entries(
  assertions.reduce((acc, a) => {
    acc[a.file] ??= { passed: 0, failed: 0 };
    acc[a.file][a.status === "passed" ? "passed" : "failed"]++;
    return acc;
  }, {}),
).sort(([a], [b]) => a.localeCompare(b));

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

const mark = (status) => (status === "passed" ? "✅" : status === "missing" ? "⚠️" : "❌");
const cell = (s) => String(s ?? "—").replace(/\|/g, "\\|").replace(/\n/g, " ");

