function detailLines(obs) {
  const out = [];
  for (const [k, v] of Object.entries(obs ?? {})) {
    if (k === "summary") continue;
    if (Array.isArray(v)) {
      out.push(`- **${k}**:`);
      for (const item of v) out.push(`  - ${typeof item === "object" ? JSON.stringify(item) : item}`);
    } else if (v && typeof v === "object") {
      out.push(`- **${k}**: ${Object.entries(v).map(([a, b]) => `${a} = ${b}`).join(" · ")}`);
    } else out.push(`- **${k}**: ${v}`);
  }
  return out;
}

function render(lang) {
  const t = T[lang];
  const L = [];
  const statusWord = allPassed ? `✅ **${t.pass}**` : `❌ **${t.fail}**`;
  L.push(`# ${t.title}`, "", `${t.other}`, "", `> ${t.generated}`, "");
  L.push(`## ${t.summary}`, "");
  L.push(`| | |`, `|---|---|`);
  L.push(`| ${t.overall} | ${statusWord} |`);
  L.push(`| ${t.acceptance} | ${acceptancePassed}/${plan.cases.length} |`);
  L.push(`| ${t.browser} | ${e2e ? `${e2ePassed}/${e2e.results.length}` : "—"} |`);
  L.push(`| ${t.suite} | ${vitest.numPassedTests}/${vitest.numTotalTests} (${files.length} files) |`);
  L.push(`| ${t.pageErrors} | ${e2e ? e2e.pageErrors.length : "—"} |`);
  L.push(`| ${t.date} | ${date} |`);
  L.push(`| ${t.commit} | \`${commit.slice(0, 10)}\` |`);
  L.push(`| ${t.tree} | ${dirty.length ? t.dirtyTxt(dirty.length) : t.clean} |`, "");

  L.push(`### ${t.perScenario}`, "");
  L.push(`| ${t.scenario} | ${t.acceptance} | ${t.browser} | ${t.result} |`, "|---|---|---|---|");
  for (const sc of plan.scenarios) {
    const cases = plan.cases.filter((c) => c.scenario === sc.id);
    const ok = cases.filter((c) => caseResult(c.id) === "passed").length;
    const br = e2eFor(sc.id);
    const brOk = br.filter((r) => r.status === "passed").length;
    const good = ok === cases.length && brOk === br.length;
    L.push(`| [${sc[t.nameKey]}](#${sc.id.toLowerCase()}) | ${ok}/${cases.length} | ${e2e ? `${brOk}/${br.length}` : "—"} | ${good ? "✅" : "❌"} |`);
  }
  L.push("");

  L.push(`## ${t.reproduce}`, "", t.reproduceText, "", "```bash", "npm ci", "npm run test:evidence   # Vitest: full suite + acceptance evidence (JSON)", "npm run build", "npm run test:e2e        # Playwright: browser checks against the production build + screenshots", "npm run test:report     # regenerates this report", "```", "");

  L.push(`## ${t.env}`, "", "| | |", "|---|---|");
  L.push(`| Node.js | ${process.version} |`, `| OS | ${process.platform} ${process.arch} |`);
  L.push(`| Next.js | ${pkgVersion("next")} |`, `| Vitest | ${pkgVersion("vitest")} |`);
  if (e2e) L.push(`| Browser | ${e2e.browser} · ${e2e.viewport} · ${e2e.target} |`);
  L.push("");

  L.push(`## ${t.scope}`, "");
  for (const s of t.scopeItems) L.push(`- ${s}`);
  L.push("", `_${t.observedLang}_`, "");

  for (const sc of plan.scenarios) {
    L.push(`<a id="${sc.id.toLowerCase()}"></a>`, "", `## ${sc[t.nameKey]}`, "");
    L.push(`| ${t.caseTable.join(" | ")} |`, `|${t.caseTable.map(() => "---").join("|")}|`);
    for (const c of plan.cases.filter((x) => x.scenario === sc.id)) {
      L.push(`| **${c.id}** | ${t.step(c.step)} | ${cell(c[t.expectedKey])} | ${cell(evidence[c.id]?.summary)} | ${mark(caseResult(c.id))} |`);
    }
    L.push("", "<details>", `<summary>${t.details}</summary>`, "");
    for (const c of plan.cases.filter((x) => x.scenario === sc.id)) {
      L.push(`**${c.id}** — ${cell(c[t.requirementKey])}`, "", ...detailLines(evidence[c.id]), "");
    }
    L.push("</details>", "");

    const br = e2eFor(sc.id);
    if (!e2e) L.push(t.noE2e, "");
    else if (br.length) {
      L.push(`| ${t.browserTable.join(" | ")} |`, `|${t.browserTable.map(() => "---").join("|")}|`);
      for (const r of br) {
        L.push(`| **${r.id}** | ${r.covers.join(", ")} | ${cell(r.expected)} | ${cell(r.observed)} | ${mark(r.status)} | ${r.screenshot ? `[PNG](test-results/${r.screenshot})` : "—"} |`);
      }
      const shots = br.filter((r) => r.screenshot);
      if (shots.length) {
        L.push("", "<details>", `<summary>${t.shots}</summary>`, "");
        for (const r of shots) L.push(`**${r.id}** — ${r.description}`, "", `<img src="test-results/${r.screenshot}" alt="${r.id}" width="720" />`, "");
        L.push("</details>");
      }
      L.push("");
    }
  }

  L.push(`## ${t.trace}`, "", `| ${t.traceTable.join(" | ")} |`, "|---|---|---|");
  for (const step of ["MEASURE", "UNDERSTAND", "ACT", "COMMUNICATE"]) {
    const cases = plan.cases.filter((c) => c.step === step);
    const br = (e2e?.results ?? []).filter((r) => r.covers.some((id) => cases.some((c) => c.id === id)));
    L.push(`| ${t.step(step)} | ${cases.map((c) => `${c.id} ${mark(caseResult(c.id))}`).join(" · ")} | ${br.map((r) => `${r.id} ${mark(r.status)}`).join(" · ") || "—"} |`);
  }
  L.push("");

  L.push(`## ${t.suiteTitle}`, "", `| ${t.suiteTable.join(" | ")} |`, "|---|---|---|");
  for (const [f, c] of files) L.push(`| \`${f}\` | ${c.passed} | ${c.failed} |`);
  L.push(`| **Total** | **${vitest.numPassedTests}** | **${vitest.numFailedTests}** |`, "");

  L.push(`## ${t.raw}`, "");
  L.push("- [`test-results/vitest-results.json`](test-results/vitest-results.json)");
  L.push("- [`test-results/acceptance-evidence.json`](test-results/acceptance-evidence.json)");
  if (e2e) L.push("- [`test-results/e2e-results.json`](test-results/e2e-results.json) · [`test-results/e2e/`](test-results/e2e/)");
  L.push("- [`../tests/acceptance/test-plan.json`](../tests/acceptance/test-plan.json) · [`../tests/acceptance/scenarios.acceptance.test.ts`](../tests/acceptance/scenarios.acceptance.test.ts) · [`../scripts/e2e-scenarios.cjs`](../scripts/e2e-scenarios.cjs)", "");

  writeFileSync(join(ROOT, t.file), L.join("\n"));
  console.log(`wrote ${t.file}`);
}

render("en");
render("pt");
console.log(`acceptance ${acceptancePassed}/${plan.cases.length} · browser ${e2e ? `${e2ePassed}/${e2e.results.length}` : "not run"} · suite ${vitest.numPassedTests}/${vitest.numTotalTests} · ${allPassed ? "PASSED" : "FAILED"}`);
process.exitCode = allPassed ? 0 : 1;
