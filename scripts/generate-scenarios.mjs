#!/usr/bin/env node
/**
 * Generates the SIMULATED demonstration scenarios used by ASTRA Health.
 *
 *   node scripts/generate-scenarios.mjs
 *
 * Output: src/data/scenarios/{nominal,vital-deviation,sensor-fault}.json
 *
 * The data is synthetic: smooth curves plus seeded pseudo-random noise. It is
 * NOT derived from any real person, mission or NASA dataset. A fixed seed keeps
 * the files reproducible so automated tests are deterministic.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "scenarios");
const N = 180; // samples per scenario
const INTERVAL = 10; // seconds of mission time between samples
const ONSET = 60; // incident onset index

const DISCLAIMER =
  "SIMULATED DEMONSTRATION DATA — synthetic values generated by scripts/generate-scenarios.mjs. Not real astronaut data, not from a NASA dataset, not for medical use.";

/** Mulberry32 seeded PRNG. */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const round = (v, d = 0) => Math.round(v * 10 ** d) / 10 ** d;
const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));
const smoothstep = (x) => {
  const c = clamp(x, 0, 1);
  return c * c * (3 - 2 * c);
};

/** Baseline (nominal) signals — periodic so the nominal recording can loop seamlessly. */
function baseline(i, r) {
  const phase = (2 * Math.PI * i) / N;
  const noise = (amp) => (r() * 2 - 1) * amp;
  return {
    hr: 71 + 3 * Math.sin(2 * phase) + noise(2),
    spo2: 97.9 + 0.4 * Math.sin(phase) + noise(0.7),
    temp: 36.72 + 0.12 * Math.sin(phase) + noise(0.05),
    quality: {
      hr: round(0.93 + noise(0.05), 2),
      spo2: round(0.92 + noise(0.05), 2),
      temp: round(0.96 + noise(0.03), 2),
    },
  };
}

function finalize(s, i) {
  return {
    t: i * INTERVAL,
    hr: s.hr === null ? null : round(clamp(s.hr, 20, 240)),
    spo2: s.spo2 === null ? null : round(clamp(s.spo2, 40, 100)),
    temp: s.temp === null ? null : round(s.temp, 1),
    quality: {
      hr: clamp(s.quality.hr, 0, 1),
      spo2: clamp(s.quality.spo2, 0, 1),
      temp: clamp(s.quality.temp, 0, 1),
    },
  };
}

function nominal() {
  const seed = 1101;
  const r = rng(seed);
  const samples = Array.from({ length: N }, (_, i) => finalize(baseline(i, r), i));
  return {
    id: "nominal",
    name: "Scenario 1 — Nominal monitoring",
    shortName: "Nominal",
    description:
      "All simulated vital signs stay inside the demo reference ranges and all sensors report good signal quality. The system keeps monitoring and nothing needs to be done.",
    incidentOnsetIndex: null,
    playbackStartIndex: 50,
    loop: true,
    confirmationReading: { hr: 72, spo2: 98, temp: 36.7, quality: 0.97 },
    generator: { script: "scripts/generate-scenarios.mjs", seed },
    samples,
  };
}

function vitalDeviation() {
  const seed = 2202;
  const r = rng(seed);
  const RAMP = 12;
  const samples = Array.from({ length: N }, (_, i) => {
    const s = baseline(i, r);
    const k = i < ONSET ? 0 : smoothstep((i - ONSET) / RAMP);
    s.hr += k * 58; // ≈ 72 → 130 bpm
    s.spo2 -= k * 9.6; // ≈ 98 → 88 %
    s.temp += k * 1.05; // ≈ 36.7 → 37.8 °C
    return finalize(s, i);
  });
  return {
    id: "vital-deviation",
    name: "Scenario 2 — Simulated vital-sign deviation",
    shortName: "Vital deviation",
    description:
      "Starting at the incident onset, simulated heart rate rises while oxygen saturation falls and temperature increases slightly. Sensor quality stays good, so the readings are consistent with each other.",
    incidentOnsetIndex: ONSET,
    playbackStartIndex: ONSET - 2,
    loop: false,
    confirmationReading: { hr: 124, spo2: 89, temp: 37.8, quality: 0.95 },
    generator: { script: "scripts/generate-scenarios.mjs", seed },
    samples,
  };
}

function sensorFault() {
  const seed = 3303;
  const r = rng(seed);
  const samples = Array.from({ length: N }, (_, i) => {
    const s = baseline(i, r);
    if (i >= ONSET) {
      // The pulse-oximeter loses skin contact: erratic low values, poor quality, dropouts.
      const k = i - ONSET;
      s.spo2 = 77 + Math.sin(k * 1.7) * 7 + (r() * 2 - 1) * 3;
      s.quality.spo2 = round(0.18 + r() * 0.17, 2);
      if (k >= 2 && k % 5 === 2) s.spo2 = null; // periodic dropouts
    }
    return finalize(s, i);
  });
  return {
    id: "sensor-fault",
    name: "Scenario 3 — Sensor fault / inconsistent reading",
    shortName: "Sensor fault",
    description:
      "At the incident onset the simulated pulse oximeter starts reporting erratic, very low SpO₂ values with poor signal quality and dropouts, while heart rate and temperature stay steady. The pattern points to a sensor problem that the crew must confirm.",
    incidentOnsetIndex: ONSET,
    playbackStartIndex: ONSET - 2,
    loop: false,
    confirmationReading: { hr: 71, spo2: 98, temp: 36.7, quality: 0.96 },
    generator: { script: "scripts/generate-scenarios.mjs", seed },
    samples,
  };
}

mkdirSync(OUT_DIR, { recursive: true });
for (const scenario of [nominal(), vitalDeviation(), sensorFault()]) {
  const file = {
    id: scenario.id,
    name: scenario.name,
    shortName: scenario.shortName,
    description: scenario.description,
    simulated: true,
    disclaimer: DISCLAIMER,
    crewMember: "Crew Member A (simulated)",
    sampleIntervalSec: INTERVAL,
    incidentOnsetIndex: scenario.incidentOnsetIndex,
    playbackStartIndex: scenario.playbackStartIndex,
    loop: scenario.loop,
    confirmationReading: scenario.confirmationReading,
    generator: scenario.generator,
    samples: scenario.samples,
  };
  const path = join(OUT_DIR, `${scenario.id}.json`);
  writeFileSync(path, JSON.stringify(file, null, 1) + "\n");
  console.log(`wrote ${path} (${file.samples.length} samples)`);
}
