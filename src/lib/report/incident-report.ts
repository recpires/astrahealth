/**
 * Structured incident report sent to Earth.
 *
 * The report only contains information produced by the simulation (readings,
 * rule findings, crew actions). It contains no diagnosis and no treatment.
 */
import { REFERENCE_CONFIG, formatVital } from "@/config/reference-ranges";
import { NASA_RESOURCE, isResourceConfirmed } from "@/config/scientific-sources";
import { EVIDENCE_LIBRARY, TOPIC_LABEL } from "@/config/evidence-library";
import type { SupportAssessment } from "@/lib/response/escalation";
import { formatMET } from "@/lib/time";
import {
  VITAL_KEYS,
  type AttentionLevel,
  type Confirmation,
  type EffectiveAnalysis,
  type OverallStatus,
  type ScenarioData,
  type SensorStatus,
  type VitalKey,
} from "@/lib/types";

export type ActionKind = "system" | "crew" | "procedure" | "confirmation" | "comms";

export interface ActionEntry {
  id: string;
  t: number;
  kind: ActionKind;
  text: string;
}

export const REPORT_FORMAT = "ASTRA-IR/0.1";

export interface IncidentReport {
  reportId: string;
  format: typeof REPORT_FORMAT;
  simulated: true;
  disclaimer: string;
  generatedAt: string;
  generatedAtSec: number;
  crewMember: string;
  scenario: { id: string; name: string };
  assessment: {
    attentionLevel: AttentionLevel;
    status: OverallStatus;
    summary: string;
    dataReliability: { score: number; label: string };
  };
  latestVitals: {
    vital: VitalKey;
    label: string;
    value: string;
    unit: string;
    signalQuality: number;
    sensorStatus: SensorStatus;
    excluded: boolean;
  }[];
  activeFindings: { title: string; level: AttentionLevel; category: string; evidence: string; since: string }[];
  resolvedFindings: { title: string; reason: string }[];
  confirmations: { vital: string; outcome: string; reading: string; at: string }[];
  actionsTaken: { at: string; text: string }[];
  medicalSupport: { urgency: string; headline: string; reasons: string[] };
  requestToGround: string;
  scientificBasis: { referenceRanges: string; nasaResource: string; evidenceContext: string };
}

export interface ReportInput {
  reportId: string;
  generatedAtSec: number;
  scenario: ScenarioData;
  analysis: EffectiveAnalysis;
  support: SupportAssessment;
  confirmations: Confirmation[];
  actions: ActionEntry[];
  openedAt: Record<string, number>;
}

const OUTCOME_TEXT: Record<Confirmation["outcome"], string> = {
  artifact: "Not reproduced — attributed to sensor",
  confirmed: "Reproduced — deviation confirmed",
  unable: "Crew unable to take a confirmation reading",
};

export function buildIncidentReport(input: ReportInput): IncidentReport {
  const { analysis, support, scenario } = input;
  const cfg = REFERENCE_CONFIG;

  const request =
    support.urgency === "urgent"
      ? "PRIORITY: Request flight surgeon review of the attached simulated data and guidance through approved procedures."
      : support.required
        ? "Request flight surgeon review of the attached simulated data."
        : analysis.excludedVitals.length > 0
          ? "For information: sensor event handled on board. No medical support requested."
          : "For information: routine status. No action requested.";

  return {
    reportId: input.reportId,
    format: REPORT_FORMAT,
    simulated: true,
    disclaimer:
      "SIMULATED DEMONSTRATION REPORT — generated by ASTRA Health from synthetic data. Not real astronaut data. Not a diagnosis. Not clinically validated.",
    generatedAt: formatMET(input.generatedAtSec),
    generatedAtSec: input.generatedAtSec,
    crewMember: scenario.crewMember,
    scenario: { id: scenario.id, name: scenario.name },
    assessment: {
      attentionLevel: analysis.level,
      status: analysis.status,
      summary: analysis.summary,
      dataReliability: { score: analysis.reliability.score, label: analysis.reliability.label },
    },
    latestVitals: VITAL_KEYS.map((k) => ({
      vital: k,
      label: cfg.vitals[k].label,
      value: formatVital(k, analysis.sensors[k].lastValue, cfg),
      unit: cfg.vitals[k].unit,
      signalQuality: Math.round(analysis.sensors[k].quality * 100) / 100,
      sensorStatus: analysis.sensors[k].status,
      excluded: analysis.excludedVitals.includes(k),
    })),
    activeFindings: analysis.findings.map((f) => ({
      title: f.title,
      level: f.level,
      category: f.category,
      evidence: f.evidence,
      since: formatMET(input.openedAt[f.id] ?? analysis.t),
    })),
    resolvedFindings: analysis.resolved.map((r) => ({ title: r.finding.title, reason: r.reason })),
    confirmations: input.confirmations.map((c) => ({
      vital: cfg.vitals[c.vital].label,
      outcome: OUTCOME_TEXT[c.outcome],
      reading: c.reading ? `${formatVital(c.vital, c.reading[c.vital], cfg)} ${cfg.vitals[c.vital].unit}` : "—",
      at: formatMET(c.t),
    })),
    actionsTaken: input.actions.map((a) => ({ at: formatMET(a.t), text: a.text })),
    medicalSupport: { urgency: support.urgency, headline: support.headline, reasons: support.reasons },
    requestToGround: request,
    scientificBasis: {
      referenceRanges: `${cfg.status}: ${cfg.provenance}`,
      nasaResource: isResourceConfirmed()
        ? `${NASA_RESOURCE.name} (${NASA_RESOURCE.origin}) — ${NASA_RESOURCE.effectiveUse}`
        : "Pending team confirmation — no NASA source for thresholds integrated yet.",
      evidenceContext: `Context only, no threshold derived: ${EVIDENCE_LIBRARY.length} NASA HRP evidence reports (${EVIDENCE_LIBRARY.map((e) => TOPIC_LABEL[e.topic].toLowerCase()).join(", ")}) listed in Science & Limits.`,
    },
  };
}

/** Plain-text rendering used for the transmission preview. */
export function reportToText(r: IncidentReport): string {
  const lines: string[] = [];
  lines.push(`${r.format} ${r.reportId} — ${r.generatedAt}`);
  lines.push(r.disclaimer);
  lines.push("");
  lines.push(`CREW: ${r.crewMember}`);
  lines.push(`SCENARIO: ${r.scenario.name}`);
  lines.push(`ATTENTION: ${r.assessment.attentionLevel} | DATA RELIABILITY: ${r.assessment.dataReliability.label} (${r.assessment.dataReliability.score}%)`);
  lines.push(`SUMMARY: ${r.assessment.summary}`);
  lines.push("");
  lines.push("LATEST VITALS (simulated):");
  for (const v of r.latestVitals) {
    lines.push(`  - ${v.label}: ${v.value} ${v.unit} | quality ${Math.round(v.signalQuality * 100)}% | sensor ${v.sensorStatus}${v.excluded ? " | EXCLUDED" : ""}`);
  }
  lines.push("");
  lines.push(`ACTIVE FINDINGS (${r.activeFindings.length}):`);
  for (const f of r.activeFindings) lines.push(`  - [${f.level}] ${f.title} (since ${f.since}) — ${f.evidence}`);
  if (r.resolvedFindings.length) {
    lines.push(`RESOLVED BY CREW CONFIRMATION (${r.resolvedFindings.length}):`);
    for (const f of r.resolvedFindings) lines.push(`  - ${f.title} — ${f.reason}`);
  }
  if (r.confirmations.length) {
    lines.push("CONFIRMATIONS:");
    for (const c of r.confirmations) lines.push(`  - ${c.at} ${c.vital}: ${c.outcome} (${c.reading})`);
  }
  lines.push("");
  lines.push(`ACTIONS TAKEN (${r.actionsTaken.length}):`);
  for (const a of r.actionsTaken) lines.push(`  - ${a.at} ${a.text}`);
  lines.push("");
  lines.push(`MEDICAL SUPPORT: ${r.medicalSupport.headline} [${r.medicalSupport.urgency}]`);
  for (const reason of r.medicalSupport.reasons) lines.push(`  - ${reason}`);
  lines.push(`REQUEST: ${r.requestToGround}`);
  lines.push("");
  lines.push(`REFERENCE RANGES: ${r.scientificBasis.referenceRanges}`);
  lines.push(`NASA SOURCE FOR THRESHOLDS: ${r.scientificBasis.nasaResource}`);
  lines.push(`SCIENTIFIC CONTEXT: ${r.scientificBasis.evidenceContext}`);
  return lines.join("\n");
}
